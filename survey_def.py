def _idx(seq, v):
    return seq.index(v) if v in seq else -1


def judge_part(p):
    """p = {'duration','intensity','frequency',...} → 'pain' | 'manage' | 'complaint' | None"""
    if not p:
        return None
    dur_ok = _idx(DURATION, p.get('duration')) >= 2        # 1주일 이상
    freq_ok = _idx(FREQUENCY, p.get('frequency')) >= 2     # 1달에 1번 이상
    inten = _idx(INTENSITY, p.get('intensity'))
    if dur_ok and freq_ok and inten >= 2:
        return 'pain'
    if (dur_ok or freq_ok) and inten >= 1:
        return 'manage'
    return 'complaint'


